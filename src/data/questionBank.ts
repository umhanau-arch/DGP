function difficulty(text: string): QuestionDifficulty {
  if (/erkläre|nenne|was ist|wofür/i.test(text)) return "leicht";
  if (/berechn|formel|matrix|integration|mining|footprint/i.test(text))
    return "schwer";
  return "mittel";
}

function topicForChapter(id: ChapterId): QuestionTopic {
  switch (id) {
    case "kapitel-1": return "Grundbegriffe";
    case "kapitel-2": return "Modellierung";
    case "kapitel-3": return "BPMN";
    case "kapitel-4": return "Petrinetze";
    case "kapitel-5": return "Wertschöpfung";
    case "kapitel-6": return "PKR";
    case "kapitel-7": return "Process-Mining";
    case "kapitel-8": return "Digitalisierung";
    case "kapitel-9": return "Grundbegriffe";
  }
}

// Build chapter-derived questions
const chapterQuestions: QuestionItem[] = [];
for (const ch of chapters) {
  for (const q of ch.quiz) {
    chapterQuestions.push({
      id: `quiz-${ch.id}-${q.id}`,
      topic: topicForChapter(ch.id),
      chapter: ch.id,
      difficulty: difficulty(q.question),
      question: q.question,
      answer: q.answer,
      why: q.why,
      source: `Kapitel ${ch.number} Quiz`,
    });
  }
  for (const grp of ch.groups) {
    for (const block of grp.blocks) {
      if (block.miniCheck) {
        chapterQuestions.push({
          id: `check-${ch.id}-${block.id}`,
          topic: topicForChapter(ch.id),
          chapter: ch.id,
          difficulty: "leicht",
          question: block.miniCheck.prompt,
          answer:
            block.miniCheck.options[block.miniCheck.correctIndex] +
            " — " +
            block.miniCheck.explain,
          choices: block.miniCheck.options,
          correctChoice: block.miniCheck.correctIndex,
          source: `Kapitel ${ch.number} Mini-Check`,
        });
      }
    }
  }
}

